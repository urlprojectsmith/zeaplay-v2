export type MessageNamespace = keyof (typeof messages)['en'];

export function translate(locale: Locale, key: `${MessageNamespace}.${string}`): string {
  const [namespace, name] = key.split('.') as [MessageNamespace, string];
  const value =
    (messages[locale][namespace] as Record<string, string | undefined>)[name] ??
    (messages.en[namespace] as Record<string, string | undefined>)[name];
  return value ?? key;
}
